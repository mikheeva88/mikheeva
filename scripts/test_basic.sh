#!/bin/sh
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RUN="$ROOT/run.sh"
VFSDIR="$ROOT/vfs_data"
EX="$ROOT/examples"
python3 "$ROOT/tools/make_vfs.py" "$VFSDIR"

echo "[1/4] No parameters"
"$RUN"
echo "[2/4] Only --vfs"
"$RUN" --vfs "$VFSDIR/minimal.zip"
echo "[3/4] Only --script"
"$RUN" --script "$EX/basic.txt"
echo "[4/4] Both parameters"
"$RUN" --vfs "$VFSDIR/minimal.zip" --script "$EX/basic.txt"
